"""Vehicle Tracker Sensor"""
import logging

from homeassistant.components.device_tracker import SourceType, TrackerEntity
from homeassistant.const import ATTR_ENTITY_PICTURE, Platform
from homeassistant.core import callback, HomeAssistant
from homeassistant.helpers import entity_registry as er
from homeassistant.helpers.event import async_track_state_change_event

from . import FordPassEntity
from .const import DOMAIN
from .const_shared import COORDINATOR_KEY
from .const_tags import Tag
from .fordpass_handler import FordpassDataHandler, UNSUPPORTED

_LOGGER = logging.getLogger(__name__)


async def async_setup_entry(hass: HomeAssistant, config_entry, async_add_entities):
    """Add the Entities from the config."""
    coordinator = hass.data[DOMAIN][config_entry.entry_id][COORDINATOR_KEY]
    _LOGGER.debug(f"{coordinator.vli}DEVICE_TRACKER async_setup_entry")

    # Added a check to see if the car supports GPS
    if FordpassDataHandler.get_gps_state(coordinator.data) != UNSUPPORTED:
        async_add_entities([FordPassCarTracker(coordinator)], True)
    else:
        _LOGGER.debug(f"{coordinator.vli}Vehicle does not support GPS")


def vehicle_image_entity_id(hass: HomeAssistant, vin: str) -> str:
    """Return the registered image entity ID for a vehicle."""
    unique_id = f"fordpass_uid_{vin}_{Tag.VEHICLE_IMAGE.key}".lower()
    registry = er.async_get(hass)
    return registry.async_get_entity_id(Platform.IMAGE, DOMAIN, unique_id) or f"{Platform.IMAGE}.fordpass_{vin}_{Tag.VEHICLE_IMAGE.key}".lower()


class FordPassCarTracker(FordPassEntity, TrackerEntity):
    def __init__(self, coordinator):
        super().__init__(entity_type=Platform.DEVICE_TRACKER, a_tag=Tag.TRACKER, coordinator=coordinator)
        self._image_entity_id: str | None = None

    async def async_added_to_hass(self):
        """Track image entity updates so its rotating token stays current."""
        await super().async_added_to_hass()
        self._image_entity_id = vehicle_image_entity_id(self.hass, self.coordinator._vin)
        self.async_on_remove(
            async_track_state_change_event(
                self.hass,
                [self._image_entity_id],
                self._handle_image_entity_state_change)
        )

    @callback
    def _handle_image_entity_state_change(self, _event):
        """Refresh the tracker image URL when the image token changes."""
        self.async_write_ha_state()

    @property
    def latitude(self):
        return FordpassDataHandler.get_gps_lat(self.coordinator.data)

    @property
    def longitude(self):
        return FordpassDataHandler.get_gps_lon(self.coordinator.data)

    @property
    def source_type(self):
        """Set source type to GPS"""
        return SourceType.GPS

    @property
    def extra_state_attributes(self):
        """Return the state attributes of the tracker."""
        # we don't need units here!
        return self._tag.get_attributes(self.coordinator.data, None)

    @property
    def entity_picture(self) -> str | None:
        """Return the tokenized image URL generated by Home Assistant."""
        if not self.coordinator.data:
            return None

        if not Tag.VEHICLE_IMAGE.get_state(self.coordinator.data, None):
            return None

        image_entity_id = self._image_entity_id or vehicle_image_entity_id(self.hass, self.coordinator._vin)
        image_state = self.hass.states.get(image_entity_id)
        if image_state is None:
            return None

        return image_state.attributes.get(ATTR_ENTITY_PICTURE)

    @property
    def icon(self):
        """Return device tracker icon"""
        return "mdi:radar"